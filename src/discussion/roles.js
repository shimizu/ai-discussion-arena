/**
 * 役割ごとのsystem promptを組み立てる。
 * 参加者の顔ぶれを含めることで、誰の発言に応答しているかを見失いにくくする。
 */
export function buildSystemPrompt({ role, topic, participants }) {
  const roster = participants
    .map(({ role: r, providerLabel }) => `${ROLE_META[r].name}: ${providerLabel}`)
    .join(" / ");

  return `${ROLE_PROMPTS[role]}

# 討議テーマ
${topic}

# 参加者
${roster}

${COMMON_RULES}

# 利用できるデータ
- e-Stat（日本の政府統計）: 日本国内の人口、物価、就業、産業、貿易などの公式統計。
- World Bank World Development Indicators: 各国の経済・社会指標の長期時系列。国際比較に向く。

データが討議に必要ない論点では、無理にツールを使わないでください。`;
}

const PHASE_INSTRUCTIONS = {
  opening: `これは開会の発言です。次を行ってください。
1. テーマのどこが論点になりうるかを2〜3点に切り分ける。
2. 肯定側と否定側それぞれに、最初に答えてほしい問いを1つずつ具体的に投げる。
自分の意見は述べないこと。200〜300字程度。`,

  debate: `あなたの立場から次の発言を行ってください。300〜500字程度。
議論が同じ主張の繰り返しになりそうなら、まだ検討されていない角度へ論点を進めてください。`,

  interjection: `ここまでの議論を議長として整理してください。150〜300字程度。
- 合意できている点、対立が残る点をそれぞれ明示する。
- すれ違っている場合は、争点が「事実の認識」なのか「価値判断」なのかを切り分ける。
- 次に詰めるべき論点を1つ指定し、両者に問いを投げる。
議論が十分に尽くされ、これ以上続けても新しい論点が出ないと判断した場合に限り、発言の最後に [討議終了] と書いてください。`,

  closing: `討議の総括を行ってください。500〜800字程度。次の構成で書いてください。
1. **合意された点** — 双方が事実として受け入れた事柄。
2. **対立が残った点** — どちらの立場も譲らなかった争点と、その理由。事実認識の相違か価値判断の相違かを明示する。
3. **提出された根拠** — 討議で実際に参照されたデータと、それが何を示したか。
4. **未解決の論点** — 判断するために追加で必要なデータや検証。

無理に結論を出す必要はありません。合意に至らなかったのであれば、至らなかったと明記し、何が判断を分けたのかを書いてください。議長として、どちらが正しかったかの判定は行いません。`,
};

export function buildTurnInstruction(phase) {
  return PHASE_INSTRUCTIONS[phase] ?? PHASE_INSTRUCTIONS.debate;
}
